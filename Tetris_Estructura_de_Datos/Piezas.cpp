// ---------------------------------------------------------
// Crear una pieza
// ---------------------------------------------------------

Pieza crearPieza(TipoPieza tipo)
{
	Pieza nueva;
	
	nueva.tipo = tipo;
	
	// Aproximadamente centrada en un tablero de 10 columnas
	nueva.x = 3;
	nueva.y = 0;
	
	nueva.rotacion = 0;
	
	return nueva;
}


// ---------------------------------------------------------
// Obtener posicion X de un bloque
// ---------------------------------------------------------

int obtenerXBloque(const Pieza& pieza, int bloque)
{
	int tipo = (int)pieza.tipo;
	
	return pieza.x +
		FORMAS[tipo][pieza.rotacion][bloque][0];
}


// ---------------------------------------------------------
// Obtener posicion Y de un bloque
// ---------------------------------------------------------

int obtenerYBloque(const Pieza& pieza, int bloque)
{
	int tipo = (int)pieza.tipo;
	
	return pieza.y +
		FORMAS[tipo][pieza.rotacion][bloque][1];
}


// ---------------------------------------------------------
// Obtener color segun el tipo de pieza
// ---------------------------------------------------------

Color obtenerColorPieza(TipoPieza tipo)
{
	switch (tipo)
	{
	case I:
		return SKYBLUE;
		
	case O:
		return YELLOW;
		
	case T:
		return PURPLE;
		
	case S:
		return GREEN;
		
	case Z:
		return RED;
		
	case J:
		return BLUE;
		
	case L:
		return ORANGE;
	}
	
	return WHITE;
}


// ---------------------------------------------------------
// Dibujar pieza
// ---------------------------------------------------------

void dibujarPieza(
				  const Pieza& pieza,
				  int xTablero,
				  int yTablero,
				  int tamCelda)
{
	Color color = obtenerColorPieza(pieza.tipo);
	
	for (int bloque = 0; bloque < 4; bloque++)
	{
		int columna = obtenerXBloque(pieza, bloque);
		int fila = obtenerYBloque(pieza, bloque);
		
		int x = xTablero + columna * tamCelda;
		int y = yTablero + fila * tamCelda;
		
		DrawRectangle(
					  x + 2,
					  y + 2,
					  tamCelda - 4,
					  tamCelda - 4,
					  color
					  );
	}
}
